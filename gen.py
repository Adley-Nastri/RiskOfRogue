#!/usr/bin/env python3
"""Generate Scripts/data_gen.lua from the sheets: one Lua table (struct) per row."""
import json, os, subprocess, sys
D=os.path.dirname(os.path.abspath(__file__))
if subprocess.call([sys.executable, os.path.join(D,'preflight.py')]): sys.exit("preflight failed; not generating")
L=lambda n: json.load(open(os.path.join(D,'sheets',n)))
def lua(v):
    if isinstance(v,bool): return 'true' if v else 'false'
    if isinstance(v,(int,float)): return repr(float(v)) if isinstance(v,float) else str(v)
    if isinstance(v,list): return '{'+', '.join(lua(x) for x in v)+'}'
    return '"'+str(v).replace('\\','\\\\').replace('"','\\"')+'"'
def rows(name, sheet, cols=None):
    out=[f"-- {name}: generated from sheets/{name}.json, one row per entry"]
    out.append(f"M.{name.upper()} = {{")
    for r in sheet['rows']:
        out.append("  {"+", ".join(f"{c}={lua(r[c])}" for c in (cols or sheet['columns']))+"},")
    out.append("}")
    return "\n".join(out)
parts=["-- AUTO-GENERATED by gen.py. Edit the sheets, not this file.","local M = {}"]
parts.append(rows('items',L('items.json')))
parts.append(rows('rarities',L('rarities.json')))
parts.append(rows('difficulty_tiers',L('difficulty_tiers.json')))
parts.append(rows('orbs',L('orbs.json')))
parts.append(rows('buffs',L('buffs.json')))
parts.append(rows('procs',L('procs.json')))
parts.append(rows('item_text',L('item_text.json')))
parts.append(rows('fx',L('fx.json')))
parts.append(rows('elements',L('elements.json')))
i=L('inventory.json')
parts.append('M.INV = {\n'+'\n'.join(f'  {r["id"]} = {lua(r["value"])},' for r in i['rows'])+'\n}')
s=L('systems.json')
parts.append("-- systems: generated from sheets/systems.json\nM.SYS = {\n"+"\n".join(f"  {r['id']} = {lua(r['value'])}, -- {r['unit']}" for r in s['rows'])+"\n}")
h=L('hooks.json')
parts.append("M.HOOKS = {\n"+"\n".join(f"  {r['id']} = {lua(r['target'])}," for r in h['rows'])+"\n}")
parts.append("M.ITEM_BY_ID = {}\nfor _,it in ipairs(M.ITEMS) do M.ITEM_BY_ID[it.id] = it end\nfor _,t in ipairs(M.ITEM_TEXT) do local it = M.ITEM_BY_ID[t.id]; if it then it.desc_rich = t.rich; it.desc = t.plain; it.pickup = t.pickup end end\nM.ELEMENT_BY_ID = {}\nfor _,e in ipairs(M.ELEMENTS) do M.ELEMENT_BY_ID[e.id] = e end\nM.PROC_BY_ID = {}\nfor _,p in ipairs(M.PROCS) do M.PROC_BY_ID[p.id] = p end\nM.RARITY_BY_ID = {}\nfor _,r in ipairs(M.RARITIES) do M.RARITY_BY_ID[r.id] = r end\nreturn M\n")
out=os.path.join(D,'mod','RiskOfRogue','Scripts','data_gen.lua')
open(out,'w').write("\n\n".join(parts)); print("wrote",out)

# docs/ITEMS.md: the player-facing item list, generated from the same sheets so it never drifts
def write_items_doc():
    items = L('items.json'); txt = {r['id']: r for r in L('item_text.json')['rows']}
    els = {r['id']: r['name'] for r in L('elements.json')['rows']}
    rar = [('white', 'Common'), ('green', 'Uncommon'), ('red', 'Legendary')]
    out = ['# Items', '', 'Generated by `gen.py` from `sheets/`. Every item is in the item-orb pool.', '']
    for rid, rname in rar:
        rows = sorted([r for r in items['rows'] if r['rarity'] == rid], key=lambda r: r['name'])
        out += [f'## {rname} ({len(rows)})', '', '| Item | Element | What it does |', '|---|---|---|']
        for r in rows:
            el = '' if r['element'] == 'none' else els.get(r['element'], r['element'])
            out.append(f"| **{r['name']}** <br>*{txt[r['id']]['pickup']}* | {el} | {txt[r['id']]['plain']} |")
        out.append('')
    sk = items.get('skipped', {})
    out += [f'## Left out ({len(sk)})', '', "Risk of Rain 2 items whose mechanic doesn't exist in Deadzone: Rogue, or that throw or fire objects Deadzone doesn't have.", '',
            '| RoR2 item (internal name) | Why |', '|---|---|']
    out += [f'| {k} | {v} |' for k, v in sorted(sk.items())]
    open(os.path.join(D, 'docs', 'ITEMS.md'), 'w').write('\n'.join(out) + '\n')
    print('wrote docs/ITEMS.md')
write_items_doc()
